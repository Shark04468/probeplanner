function buildLang(overrides, fallbackOverrides = null) {
  const out = {};
  for (const key of BASE_KEYS) {
    const fallback = (fallbackOverrides && fallbackOverrides[key]) || humanizeKey(key);
    out[key] = String(overrides[key] || fallback);
  }
  return out;
}

